package docs

// AsyncAPI projection of the event model. One-way: nothing in craftgo
// reads the document back.

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
	"sigs.k8s.io/yaml"

	"github.com/craftgodotdev/craftgo/internal/ast"
	"github.com/craftgodotdev/craftgo/internal/config"
	"github.com/craftgodotdev/craftgo/internal/semantic"
)

// asyncAPIDoc is the subset of AsyncAPI 3.0 the event model projects
// onto. Maps marshal with sorted keys, so the document is diff-stable.
type asyncAPIDoc struct {
	AsyncAPI   string                     `json:"asyncapi"`
	Info       asyncAPIInfo               `json:"info"`
	Channels   map[string]asyncAPIChannel `json:"channels,omitempty"`
	Operations map[string]asyncAPIOp      `json:"operations,omitempty"`
	Components asyncAPIComponents         `json:"components"`
}

type asyncAPIInfo struct {
	Title       string `json:"title"`
	Version     string `json:"version"`
	Description string `json:"description,omitempty"`
}

type asyncAPIChannel struct {
	Address     string                 `json:"address"`
	Title       string                 `json:"title,omitempty"`
	Description string                 `json:"description,omitempty"`
	Deprecated  bool                   `json:"deprecated,omitempty"`
	Messages    map[string]asyncAPIRef `json:"messages,omitempty"`
}

type asyncAPIOp struct {
	// Action is "send" for the service that publishes the contract and
	// "receive" for each service that consumes it.
	Action      string      `json:"action"`
	Channel     asyncAPIRef `json:"channel"`
	Title       string      `json:"title,omitempty"`
	Description string      `json:"description,omitempty"`
	Deprecated  bool        `json:"deprecated,omitempty"`
	// Group is the consumer's broker identity, on a receive operation
	// only. AsyncAPI has no field for it, so it rides as an extension:
	// it is what an evolution check compares to catch a rename that
	// would leave consumers with no committed position.
	Group    string        `json:"x-craftgo-group,omitempty"`
	Messages []asyncAPIRef `json:"messages,omitempty"`
}

type asyncAPIComponents struct {
	Messages map[string]asyncAPIMessage `json:"messages,omitempty"`
	Schemas  map[string]any             `json:"schemas,omitempty"`
}

type asyncAPIMessage struct {
	Name        string       `json:"name"`
	Title       string       `json:"title,omitempty"`
	Summary     string       `json:"summary,omitempty"`
	ContentType string       `json:"contentType,omitempty"`
	Deprecated  bool         `json:"deprecated,omitempty"`
	Payload     *asyncAPIRef `json:"payload,omitempty"`
}

type asyncAPIRef struct {
	Ref string `json:"$ref"`
}

// GenerateAsyncAPI writes the AsyncAPI projection to
// `events.asyncapi`. Skipped when the path is disabled or the design
// declares no event.
func GenerateAsyncAPI(proj *semantic.Project, cfg *config.Config, projectRoot string) error {
	dest := cfg.Events.AsyncAPI
	if dest == "" || dest == "-" || !proj.HasEvents() {
		return nil
	}
	doc, err := buildAsyncAPIDoc(proj, cfg)
	if err != nil {
		return err
	}
	out, err := yaml.Marshal(doc)
	if err != nil {
		return fmt.Errorf("marshal asyncapi: %w", err)
	}
	full := filepath.Join(projectRoot, dest)
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		return err
	}
	header := []byte("# Generated by craftgo. DO NOT EDIT.\n")
	return os.WriteFile(full, append(header, out...), 0o644)
}

// buildAsyncAPIDoc projects the event model onto an AsyncAPI document.
// Payload schemas come from the same builder the OpenAPI document uses,
// so a type is described identically in both.
func buildAsyncAPIDoc(proj *semantic.Project, cfg *config.Config) (*asyncAPIDoc, error) {
	schemas, resolve, err := asyncAPISchemas(proj)
	if err != nil {
		return nil, err
	}
	roots := map[string]bool{}
	for _, ev := range proj.Events() {
		if name := payloadComponent(resolve, ev); name != "" {
			roots[name] = true
		}
	}
	doc := &asyncAPIDoc{
		AsyncAPI: "3.0.0",
		Info: asyncAPIInfo{
			Title:       orDefault(cfg.OpenAPI.Title, "craftgo events"),
			Version:     orDefault(cfg.OpenAPI.Version, "0.1.0"),
			Description: cfg.OpenAPI.Description,
		},
		Channels:   map[string]asyncAPIChannel{},
		Operations: map[string]asyncAPIOp{},
		Components: asyncAPIComponents{
			Messages: map[string]asyncAPIMessage{},
			Schemas:  reachableSchemas(schemas, roots),
		},
	}
	for _, ev := range proj.Events() {
		messageID := componentID(ev.Contract)
		doc.Components.Messages[messageID] = asyncAPIMessage{
			Name:       ev.Contract,
			Title:      ev.Name,
			Summary:    decoratorDoc(ev.Decl.Decorators),
			Deprecated: ast.HasDecorator(ev.Decl.Decorators, "deprecated"),
			Payload:    payloadRef(resolve, ev),
		}
		doc.Channels[ev.Contract] = asyncAPIChannel{
			Address:     ev.Contract,
			Title:       ev.Name,
			Description: decoratorDoc(ev.Decl.Decorators),
			Deprecated:  ast.HasDecorator(ev.Decl.Decorators, "deprecated"),
			Messages:    map[string]asyncAPIRef{messageID: {Ref: "#/components/messages/" + messageID}},
		}
		if !ev.HasProducer() {
			// The channel and its message still describe the contract; only
			// the claim that this application sends it is withheld.
			continue
		}
		doc.Operations[componentID(ev.Service+"."+ev.Name+".Send")] = asyncAPIOp{
			Action:      "send",
			Channel:     asyncAPIRef{Ref: "#/channels/" + ev.Contract},
			Title:       ev.Service + " publishes " + ev.Name,
			Description: decoratorDoc(ev.Decl.Decorators),
			Deprecated:  ast.HasDecorator(ev.Decl.Decorators, "deprecated"),
			Messages:    []asyncAPIRef{{Ref: "#/channels/" + ev.Contract + "/messages/" + messageID}},
		}
	}
	for _, c := range proj.Consumers() {
		if c.Event.Contract == "" {
			continue
		}
		doc.Operations[componentID(c.Service+"."+c.Name+".Receive")] = asyncAPIOp{
			Action:      "receive",
			Channel:     asyncAPIRef{Ref: "#/channels/" + c.Event.Contract},
			Title:       c.Service + " consumes " + c.Event.Name,
			Description: decoratorDoc(c.Decl.Decorators),
			Deprecated:  ast.HasDecorator(c.Decl.Decorators, "deprecated"),
			Group:       c.Group,
			Messages:    []asyncAPIRef{{Ref: "#/channels/" + c.Event.Contract + "/messages/" + componentID(c.Event.Contract)}},
		}
	}
	return doc, nil
}

// payloadRef points at the merged component schema of an event's
// payload. Nil when the payload did not resolve.
func payloadRef(resolve map[symbolKey]string, ev semantic.ResolvedEvent) *asyncAPIRef {
	name := payloadComponent(resolve, ev)
	if name == "" {
		return nil
	}
	return &asyncAPIRef{Ref: "#/components/schemas/" + name}
}

// payloadComponent is the merged component name an event's payload lives
// under. A generic payload resolves to its instantiated component
// (`EnvelopeOfOrder`), since the generic declaration itself is not a
// component.
func payloadComponent(resolve map[symbolKey]string, ev semantic.ResolvedEvent) string {
	if ev.Payload != nil && ev.PayloadRef != nil && len(ev.PayloadRef.Args) > 0 {
		return genericComponentName(ev.Payload, ev.PayloadRef.Args)
	}
	return resolve[symbolKey{pkg: ev.PayloadPkg, name: ev.PayloadName}]
}

// componentID renders a name as an AsyncAPI component / operation key,
// folding characters outside the component charset to `_`. Keys derive
// from the contract name, which is project-unique; a DSL event name is
// only package-unique.
func componentID(name string) string {
	var b strings.Builder
	for _, r := range name {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '_', r == '-':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	return b.String()
}

// reachableSchemas narrows the component set to what an event payload
// reaches, following `$ref` from each payload root.
func reachableSchemas(all map[string]any, roots map[string]bool) map[string]any {
	out := map[string]any{}
	queue := make([]string, 0, len(roots))
	for name := range roots {
		queue = append(queue, name)
	}
	for len(queue) > 0 {
		name := queue[len(queue)-1]
		queue = queue[:len(queue)-1]
		schema, ok := all[name]
		if !ok {
			continue
		}
		if _, seen := out[name]; seen {
			continue
		}
		out[name] = schema
		for _, ref := range schemaRefs(schema) {
			if _, seen := out[ref]; !seen {
				queue = append(queue, ref)
			}
		}
	}
	return out
}

// schemaRefs collects every `#/components/schemas/X` target inside one
// decoded schema value.
func schemaRefs(v any) []string {
	const prefix = "#/components/schemas/"
	var out []string
	switch t := v.(type) {
	case map[string]any:
		for key, val := range t {
			if key == "$ref" {
				if ref, ok := val.(string); ok && strings.HasPrefix(ref, prefix) {
					out = append(out, strings.TrimPrefix(ref, prefix))
				}
				continue
			}
			out = append(out, schemaRefs(val)...)
		}
	case []any:
		for _, item := range t {
			out = append(out, schemaRefs(item)...)
		}
	}
	return out
}

// asyncAPISchemas renders every declaration's JSON Schema through the
// OpenAPI builder and returns them next to the (package, name) → merged
// component-name table the refs are built from.
func asyncAPISchemas(proj *semantic.Project) (map[string]any, map[symbolKey]string, error) {
	merged := mergeProjectForOpenAPI(proj)
	resolve, _ := projectResolveTable(proj)
	doc := &openapi3.T{Components: &openapi3.Components{Schemas: openapi3.Schemas{}}}
	registry := newGenericRegistry()
	registry.resolver = semantic.ResolverFor(merged, nil)
	collectGenericInstancesInPackage(merged, registry)
	names := &schemaNames{}
	addSchemas(doc, merged, registry, names)
	emitGenericInstanceComponents(doc, merged, registry, names)

	raw, err := json.Marshal(doc.Components.Schemas)
	if err != nil {
		return nil, nil, fmt.Errorf("marshal asyncapi schemas: %w", err)
	}
	var out map[string]any
	if err := yaml.Unmarshal(raw, &out); err != nil {
		return nil, nil, fmt.Errorf("decode asyncapi schemas: %w", err)
	}
	return out, resolve, nil
}

// decoratorDoc returns the `@doc` text of a declaration, or "".
func decoratorDoc(decs []*ast.Decorator) string {
	d := ast.FindDecorator(decs, "doc")
	if d == nil {
		return ""
	}
	for _, arg := range d.Args {
		for _, v := range ast.DecoratorArgValues(arg) {
			if lit, ok := v.(*ast.StringLit); ok {
				return lit.Value
			}
		}
	}
	return ""
}
