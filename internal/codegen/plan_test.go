// planSrc exercises every shape the plan has to account for: a package
// with enums and errors and one without, a service with methods, one with
// methods behind a `@group`, a consumer split into another logic folder,
// an events-only service in a second package, and a middleware.
var planSrc = []string{`package shop
enum Tier { Gold = 1  Silver = 2 }
error NotFound OrderMissing { id string }
type Order {
	id    string @minLength(1)
	tier  Tier
}
middleware AuthRequired
@prefix("/shop")
service Orders {
	get GetOrder /orders/{id} { request Order  response Order }
	post PlaceOrder /orders { request Order  response Order }
	event Placed { payload Order }
	consume Reconcile { event Placed }
}
@group("admin/v2")
extend service Orders {
	get Audit /audit { response Order }
}`, `package warehouse
type Shelf { code string @minLength(1) }
service Stock {
	get Shelves /shelves { response Shelf }
}
service Restock {
	consume OnPlaced { event shop.Placed }
}`}

// planConfig turns on every target a run can write, so the plan is
// compared against the widest output craftgo produces. A language added
// to the catalogue is turned on here.
func planConfig() *config.Config { return eventsConfig() }

// The claim a run files is a list of files it names BEFORE writing them.
// A file an emitter writes but the plan misses is unclaimed - the silent
// clobber the claim exists to stop - and one the plan names but nothing
// writes protects a path nobody owns. Either way the two must match.
func TestPlanMatchesWhatTheRunWrites(t *testing.T) {
	dir := t.TempDir()
	cfg := planConfig()
	proj := analyzeProject(t, planSrc...)
	if err := Generate(proj, cfg, dir); err != nil {
		t.Fatalf("generate: %v", err)
	}
	sel, _ := selection(nil)
	planned := map[string]bool{}
	for _, out := range plannedOutputs(proj, cfg, dir, sel) {
		for _, f := range out.Files {
			planned[f] = true
		}
	}
	written := regeneratedUnder(t, dir)
	// An empty tree would compare nothing and pass.
	if len(written) < 15 {
		t.Fatalf("the fixture regenerated %d files, too few to pin the plan", len(written))
	}

	for _, f := range sortedPaths(written) {
		if !planned[f] {
			t.Errorf("%s is regenerated but unclaimed - add it to the plan", rel(dir, f))
		}
	}
	for _, f := range sortedPaths(planned) {
		if !written[f] {
			t.Errorf("%s is claimed but nothing wrote it - drop it from the plan", rel(dir, f))
		}
	}
}

// The gen-once scaffolds are written only when missing, so two manifests
// cannot clobber one and none of them is claimed.
func TestScaffoldsAreNotClaimed(t *testing.T) {
	dir := t.TempDir()
	cfg := planConfig()
	cfg.Output.Main = "./main.go"
	proj := analyzeProject(t, planSrc...)
	if err := Generate(proj, cfg, dir); err != nil {
		t.Fatalf("generate: %v", err)
	}
	sel, _ := selection(nil)
	planned := map[string]bool{}
	for _, out := range plannedOutputs(proj, cfg, dir, sel) {
		for _, f := range out.Files {
			planned[f] = true
		}
	}
	scaffolds := 0
	_ = filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !hasPrefix(path, "// Scaffold generated by craftgo") {
			return nil
		}
		scaffolds++
		if planned[path] {
			t.Errorf("%s is a scaffold and must not be claimed", rel(dir, path))
		}
		return nil
	})
	if scaffolds == 0 {
		t.Fatal("the fixture wrote no scaffold, so the rule is untested")
	}
}

// Two manifests generating from ONE design write the same files, so both
// file the same claim and neither refuses the other - the shape several
// deployables of one design rely on.
func TestOneDesignTwoManifestsShareTheClaim(t *testing.T) {
	dir := t.TempDir()
	proj := analyzeProject(t, planSrc...)
	proj.Root = filepath.Join(dir, "design")
	if err := os.MkdirAll(proj.Root, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := Generate(proj, planConfig(), dir); err != nil {
		t.Fatalf("first manifest: %v", err)
	}
	// A second manifest over the same design and the same output files
	// the same claim.
	if err := Generate(proj, planConfig(), dir); err != nil {
		t.Fatalf("second manifest over one design must be allowed: %v", err)
	}
}

// regeneratedUnder returns every file under dir that craftgo rewrites on
// each run, by the header each one opens with.
func regeneratedUnder(t *testing.T, dir string) map[string]bool {
	t.Helper()
	out := map[string]bool{}
	err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || strings.Contains(path, claim.Dir) {
			return nil
		}
		if hasPrefix(path, "// Code generated by craftgo") || hasPrefix(path, "# Generated by craftgo") {
			out[path] = true
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func hasPrefix(path, prefix string) bool {
	body, err := os.ReadFile(path)
	return err == nil && strings.HasPrefix(string(body), prefix)
}

func sortedPaths(set map[string]bool) []string {
	out := make([]string, 0, len(set))
	for p := range set {
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}

func rel(root, path string) string {
	r, err := filepath.Rel(root, path)
	if err != nil {
		return path
	}
	return filepath.ToSlash(r)
}
