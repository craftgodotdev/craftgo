// planSrc is two packages covering the shapes the plan must name: enums,
// errors, events, a middleware, a `@group` block, and a package without events.
var planSrc = []string{`package shop
enum Tier { Gold = 1  Silver = 2 }
error NotFound OrderMissing { id string }
type Order {
	id    string @minLength(1)
	tier  Tier
}
middleware AuthRequired
event Placed { payload Order }
@prefix("/shop")
service Orders {
	get GetOrder /orders/{id} { request Order  response Order }
	post PlaceOrder /orders { request Order  response Order }
}
@group("admin/v2")
extend service Orders {
	get Audit /audit { response Order }
}`, `package warehouse
type Shelf { code string @minLength(1) }
service Stock {
	get Shelves /shelves { response Shelf }
}`}

// planConfig enables every target, so the plan meets the widest output.
func planConfig() *config.Config { return eventsConfig() }

// emitOnly runs a pass without its sweep, so the test sees every file the
// emitters wrote.
func emitOnly(t *testing.T, proj *semantic.Project, cfg *config.Config, dir string) {
	t.Helper()
	sel, _ := selection(nil)
	if err := emit(Inputs{Design: proj}, cfg, dir, sel); err != nil {
		t.Fatalf("emit: %v", err)
	}
}

// The plan names exactly the regenerated files a pass writes.
func TestPlanMatchesWhatTheRunWrites(t *testing.T) {
	dir := t.TempDir()
	cfg := planConfig()
	proj := analyzeProject(t, planSrc...)
	emitOnly(t, proj, cfg, dir)

	sel, _ := selection(nil)
	_, planned := plan(Inputs{Design: proj}, cfg, dir, sel)
	written := regeneratedUnder(t, dir)
	// An empty tree would compare nothing and pass.
	if len(written) < 15 {
		t.Fatalf("the fixture regenerated %d files, too few to pin the plan", len(written))
	}

	for _, f := range sortedPaths(written) {
		if !planned[f] {
			t.Errorf("%s is regenerated but unplanned - the sweep would delete it; add it to the plan", rel(dir, f))
		}
	}
	for _, f := range sortedPaths(planned) {
		if !written[f] {
			t.Errorf("%s is planned but nothing wrote it - drop it from the plan", rel(dir, f))
		}
	}
}

// No gen-once scaffold is planned, and each survives the sweep, svccontext.go
// in a swept directory included.
func TestScaffoldsSurviveTheSweep(t *testing.T) {
	dir := t.TempDir()
	cfg := planConfig()
	cfg.Output.Main = "./main.go"
	proj := analyzeProject(t, planSrc...)
	if err := Generate(Inputs{Design: proj}, cfg, dir); err != nil {
		t.Fatalf("generate: %v", err)
	}
	sel, _ := selection(nil)
	_, planned := plan(Inputs{Design: proj}, cfg, dir, sel)
	scaffolds := 0
	_ = filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !hasPrefix(path, "// Scaffold generated by craftgo") {
			return nil
		}
		scaffolds++
		if planned[path] {
			t.Errorf("%s is a scaffold and must not be part of the plan", rel(dir, path))
		}
		return nil
	})
	if scaffolds == 0 {
		t.Fatal("the fixture wrote no scaffold, so the rule is untested")
	}
	if _, err := os.Stat(filepath.Join(dir, "svccontext", "svccontext.go")); err != nil {
		t.Errorf("the container scaffold shares a directory with a regenerated file and must survive: %v", err)
	}
}

// The sweep never walks the project root, even when an output key resolves
// to it.
func TestTheProjectRootIsNeverSwept(t *testing.T) {
	dir := t.TempDir()
	cfg := planConfig()
	cfg.Output.Types = "."
	cfg.Output.Svccontext = "./svccontext.go"
	cfg.Output.OpenAPI = "./openapi.yaml"
	cfg.Events.Targets = []config.EventTarget{{Lang: config.LangGo, Out: "."}}
	sel, _ := selection(nil)
	dirs, _ := plan(Inputs{Design: analyzeProject(t, planSrc...)}, cfg, dir, sel)
	for _, got := range dirs {
		if got.path == filepath.Clean(dir) {
			t.Errorf("the sweep must not walk the project root, got %v", dirs)
		}
	}
}

// Where a target writes only named files into a directory - the document, wiring.go and grpc.go,
// middlewares.go - the sweep takes those files and nothing else there or below: a copy of the
// document, a docs site beside it, or a package under the wiring survives.
func TestTheSweepTakesOnlyTheFilesANamedOutputWrites(t *testing.T) {
	dir := t.TempDir()
	cfg := planConfig()
	proj := analyzeProject(t, planSrc...)
	if err := Generate(Inputs{Design: proj}, cfg, dir); err != nil {
		t.Fatalf("first pass: %v", err)
	}
	document, err := os.ReadFile(filepath.Join(dir, "docs", "openapi.yaml"))
	if err != nil {
		t.Fatalf("the first pass wrote no document: %v", err)
	}
	wiring, err := os.ReadFile(filepath.Join(dir, "internal", "wiring", "wiring.go"))
	if err != nil {
		t.Fatalf("the first pass wrote no wiring: %v", err)
	}
	kept := map[string][]byte{
		"docs/openapi.v1-frozen.yaml":      document,
		"docs/site/public/api.yaml":        document,
		"docs/site/index.md":               []byte("# notes\n"),
		"internal/wiring/wiring.go.orig":   wiring,
		"internal/wiring/v1/wiring.go":     wiring,
		"svccontext/legacy/middlewares.go": wiring,
	}
	for name, body := range kept {
		p := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, body, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := Generate(Inputs{Design: proj}, cfg, dir); err != nil {
		t.Fatalf("second pass: %v", err)
	}
	for _, name := range slices.Sorted(maps.Keys(kept)) {
		if _, err := os.Stat(filepath.Join(dir, filepath.FromSlash(name))); err != nil {
			t.Errorf("%s is no file craftgo writes and must survive: %v", name, err)
		}
	}
	if err := Generate(Inputs{Design: analyzeProject(t)}, cfg, dir); err != nil {
		t.Fatalf("pass without a DSL package: %v", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "docs", "openapi.yaml")); !os.IsNotExist(err) {
		t.Errorf("a document the run no longer writes must be swept: %v", err)
	}
}

// A file one target left in a directory another target regenerates into is swept once the
// manifest moves the first target's output out of it.
func TestSweepTakesAnotherTargetsStaleFile(t *testing.T) {
	proj := analyzeProject(t, planSrc...)
	for _, c := range []struct {
		name   string
		before func(*config.Config)
		after  func(*config.Config)
		stale  string
	}{
		{
			name:   "document under the types",
			before: func(cfg *config.Config) { cfg.Output.OpenAPI = "./internal/types/openapi.yaml" },
			after:  func(cfg *config.Config) { cfg.Output.OpenAPI = "./docs/openapi.yaml" },
			stale:  filepath.Join("internal", "types", "openapi.yaml"),
		},
	} {
		t.Run(c.name, func(t *testing.T) {
			dir := t.TempDir()
			cfg := planConfig()
			c.before(cfg)
			if err := Generate(Inputs{Design: proj}, cfg, dir); err != nil {
				t.Fatalf("first pass: %v", err)
			}
			if _, err := os.Stat(filepath.Join(dir, c.stale)); err != nil {
				t.Fatalf("the first pass wrote no %s: %v", c.stale, err)
			}
			c.after(cfg)
			if err := Generate(Inputs{Design: proj}, cfg, dir); err != nil {
				t.Fatalf("second pass: %v", err)
			}
			if _, err := os.Stat(filepath.Join(dir, c.stale)); !os.IsNotExist(err) {
				t.Errorf("%s survived the sweep (%v)", c.stale, err)
			}
		})
	}
}

// regeneratedUnder returns every file under dir that opens with craftgo's
// or a plugin's generated header.
func regeneratedUnder(t *testing.T, dir string) map[string]bool {
	t.Helper()
	out := map[string]bool{}
	err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return nil
		}
		if hasPrefix(path, golang.GeneratedHeader) || hasPrefix(path, docs.GeneratedHeader) || hasPrefix(path, protodesign.PluginHeaders[0]) || hasPrefix(path, protodesign.PluginHeaders[1]) {
			out[path] = true
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func hasPrefix(path, prefix string) bool {
	body, err := os.ReadFile(path)
	return err == nil && strings.HasPrefix(string(body), prefix)
}

func sortedPaths(set map[string]bool) []string {
	out := make([]string, 0, len(set))
	for p := range set {
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}

func rel(root, path string) string {
	r, err := filepath.Rel(root, path)
	if err != nil {
		return path
	}
	return filepath.ToSlash(r)
}
