// Every file a run REGENERATES is claimed by the design it came from, so
// two designs writing one file are refused before either is written and
// the deployables of ONE design keep sharing everything they produce
// alike. The rule lives here, over the whole run, rather than in the
// target that first needed it.

// plannedOutputs names what this run will write, grouped by the directory
// each claim is filed in. Targets that are not selected write nothing, so
// they claim nothing.
func plannedOutputs(proj *semantic.Project, cfg *config.Config, projectRoot string, sel map[string]bool) []claim.Output {
	var outs []claim.Output
	if sel[config.LangGo] {
		outs = append(outs, golang.PlannedOutputs(proj, cfg, projectRoot)...)
	}
	outs = append(outs, plannedEventOutputs(proj, cfg, projectRoot, sel)...)
	if sel[TargetDocs] {
		outs = append(outs, docs.PlannedOutputs(proj, cfg, projectRoot)...)
	}
	return mergeByRoot(outs)
}

// plannedEventOutputs is [plannedOutputs] for the language targets alone,
// which is what a run of [GenerateEventTargets] writes.
func plannedEventOutputs(proj *semantic.Project, cfg *config.Config, projectRoot string, sel map[string]bool) []claim.Output {
	var outs []claim.Output
	for _, target := range LangTargets {
		if !sel[target.Lang] {
			continue
		}
		cfgTarget, ok := cfg.Events.TargetFor(target.Lang)
		if !ok || !cfgTarget.Enabled() {
			continue
		}
		switch target.Lang {
		case config.LangGo:
			outs = append(outs, golang.PlannedEventOutputs(proj, cfg, projectRoot, cfgTarget.Out)...)
		}
	}
	return mergeByRoot(outs)
}

// mergeByRoot folds every output sharing a directory into one claim, in a
// deterministic order: several targets write into one directory, and the
// directory holds one record per design.
func mergeByRoot(outs []claim.Output) []claim.Output {
	byRoot := map[string][]string{}
	for _, out := range outs {
		byRoot[out.Root] = append(byRoot[out.Root], out.Files...)
	}
	roots := make([]string, 0, len(byRoot))
	for root := range byRoot {
		roots = append(roots, root)
	}
	sort.Strings(roots)
	merged := make([]claim.Output, 0, len(roots))
	for _, root := range roots {
		files := byRoot[root]
		sort.Strings(files)
		merged = append(merged, claim.Output{Root: root, Files: slices.Compact(files)})
	}
	return merged
}

// checkClaims refuses to write a file another design already claims. Two
// designs may share an output directory - that is how one contract set
// serves several deployables - but not a file: the second run would
// overwrite the first, and the order of the build would decide what the
// directory holds.
func checkClaims(outs []claim.Output, cfg *config.Config, designRoot, projectRoot string) error {
	for _, out := range outs {
		mine := claim.Name(claim.Key(out.Root, designRoot))
		foreign := claim.Foreign(out.Root, mine)
		if len(foreign) == 0 {
			continue
		}
		for _, file := range out.Files {
			other, taken := foreign[file]
			if !taken {
				continue
			}
			under := func(rel string) string { return show(projectRoot, filepath.Join(out.Root, filepath.FromSlash(rel))) }
			manifests := make([]string, 0, len(other.Manifests))
			for _, m := range other.Manifests {
				manifests = append(manifests, under(m))
			}
			return fmt.Errorf("%s is generated by two designs - %s, through %s, and %s, through this manifest at %s; two designs cannot write one file, so give this manifest its own output directories, or generate both deployables from the one design",
				show(projectRoot, file),
				under(other.Design), strings.Join(manifests, ", "),
				show(projectRoot, designRoot), show(projectRoot, cfg.ManifestDir))
		}
	}
	return nil
}

// pruneClaims deletes what this design wrote last run and does not write
// this one. The claim record is the only list that can identify them: a
// service the design has dropped takes its name with it, so nothing left
// in the design says which file on disk used to be its.
//
// It runs over the whole plan rather than inside one emitter, so every
// regenerated output is swept on the same terms - the handler set of a
// service that is gone, its library package, its routes, the container's
// generated files, the types folder of a DSL package that was deleted.
//
// A file goes only when it is this design's (another design's claim wins
// - that is how deployables share a contract set), the plan no longer
// names it, and it still carries the generated header, so a hand-written
// file or a gen-once scaffold at the same path stays. Gen-once scaffolds
// are never claimed, so they are never even considered.
//
// It must run after every generator and before [recordClaims], which
// overwrites the record it reads.
func pruneClaims(outs []claim.Output, designRoot string) error {
	for _, out := range outs {
		keep := make(map[string]bool, len(out.Files))
		for _, file := range out.Files {
			keep[file] = true
		}
		mine := claim.Name(claim.Key(out.Root, designRoot))
		record, filed := claim.Live(claim.Read(out.Root), out.Root)[mine]
		if !filed {
			continue
		}
		foreign := claim.Foreign(out.Root, mine)
		var emptied []string
		for _, rel := range record.Files {
			file := filepath.Join(out.Root, filepath.FromSlash(rel))
			if _, taken := foreign[file]; taken || keep[file] {
				continue
			}
			if !claim.Generated(file) {
				continue
			}
			if err := os.Remove(file); err != nil && !os.IsNotExist(err) {
				return err
			}
			emptied = append(emptied, filepath.Dir(file))
		}
		pruneEmptyDirs(out.Root, emptied)
	}
	return nil
}

// pruneEmptyDirs removes the directories a prune emptied, deepest first,
// and the parents that empties in turn. It stops at the output root: the
// directory is the claim's, and a run that leaves it bare still owns it.
func pruneEmptyDirs(root string, dirs []string) {
	sort.Sort(sort.Reverse(sort.StringSlice(dirs)))
	for _, dir := range dirs {
		for strings.HasPrefix(dir, root+string(filepath.Separator)) {
			entries, err := os.ReadDir(dir)
			if err != nil || len(entries) > 0 {
				break
			}
			if os.Remove(dir) != nil {
				break
			}
			dir = filepath.Dir(dir)
		}
	}
}

// recordClaims files this run's claim on every directory it wrote into.
func recordClaims(outs []claim.Output, cfg *config.Config, designRoot string) error {
	for _, out := range outs {
		key := claim.Key(out.Root, designRoot)
		manifest := claim.Key(out.Root, cfg.ManifestDir)
		if err := claim.Write(out.Root, claim.Name(key), key, manifest, out.Files); err != nil {
			return err
		}
	}
	return nil
}

// show renders a path the way the user typed the run: relative to the
// project root, falling back to the absolute path when it lies outside.
func show(projectRoot, path string) string {
	rel, err := filepath.Rel(projectRoot, path)
	if err != nil {
		return filepath.ToSlash(path)
	}
	return filepath.ToSlash(rel)
}
