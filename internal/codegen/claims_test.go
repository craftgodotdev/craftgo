// generatedHeader opens every file craftgo rewrites on each run; the
// scaffolds carry a different first line and are never claimed.
const generatedHeader = "// Code generated by craftgo. DO NOT EDIT."

// genInto runs the Go event target for one design against a shared project
// root, the way two manifests of a multi-deployable service do.
func genInto(t *testing.T, root, designRel, src string, out string) {
	t.Helper()
	proj := analyzeProject(t, src)
	// A claim counts only while its design folder is there, so the fixture
	// has to have one.
	proj.Root = filepath.Join(root, designRel)
	if err := os.MkdirAll(proj.Root, 0o755); err != nil {
		t.Fatal(err)
	}
	cfg := eventsConfig()
	cfg.Events.Targets = []config.EventTarget{{Lang: config.LangGo, Out: out}}
	if err := GenerateEventTargets(proj, cfg, root); err != nil {
		t.Fatalf("generate %s: %v", designRel, err)
	}
}

// notesMatching picks the notes a test means out of the whole set, so
// adding an unrelated note does not fail it.
func notesMatching(notes []string, needle string) []string {
	var out []string
	for _, n := range notes {
		if strings.Contains(n, needle) {
			out = append(out, n)
		}
	}
	return out
}

func eventDirs(t *testing.T, root, out string) []string {
	t.Helper()
	entries, err := os.ReadDir(filepath.Join(root, out))
	if err != nil {
		return nil
	}
	var got []string
	for _, e := range entries {
		if e.IsDir() && e.Name() != claim.Dir {
			got = append(got, e.Name())
		}
	}
	return got
}

const alphaSrc = `package x
type Placed { id string @minLength(1) }
service AlphaService {
	event Placed { payload Placed }
}`

const betaSrc = `package y
type Shipped { id string @minLength(1) }
service BetaService {
	event Shipped { payload Shipped }
}`

// Several manifests may write into one event output so a contract set has a
// single Go copy - the layout a service split across api, consumer and
// cronjob deployables needs. A run must delete only what it produced
// itself, whatever the others declare.
func TestPruneLeavesAnotherManifestsOutputAlone(t *testing.T) {
	const out = "./contracts/events"
	root := t.TempDir()
	for range 3 {
		genInto(t, root, "a", alphaSrc, out)
		genInto(t, root, "b", betaSrc, out)
	}
	got := eventDirs(t, root, out)
	if len(got) != 2 {
		t.Fatalf("both manifests' output must survive, got %v", got)
	}

	// One manifest dropping its last event leaves the other untouched: its
	// keep set is empty, which must not read as "everything here is mine".
	genInto(t, root, "b", `package y
type Shipped { id string @minLength(1) }
service BetaService {
	get List /list { response Shipped }
}`, out)
	got = eventDirs(t, root, out)
	if len(got) != 1 || got[0] != "alpha_service" {
		t.Errorf("dropping b's last event must clear only b, got %v", got)
	}
}

// A run still removes its own stale output - a renamed service, say. The
// inventory records what the last run wrote, so the file it no longer
// produces is the one that goes.
func TestPruneStillClearsItsOwnStaleOutput(t *testing.T) {
	const out = "./internal/events"
	root := t.TempDir()
	genInto(t, root, "design", alphaSrc, out)
	genInto(t, root, "design", `package x
type Placed { id string @minLength(1) }
service RenamedService {
	event Placed { payload Placed }
}`, out)
	got := eventDirs(t, root, out)
	if len(got) != 1 || got[0] != "renamed_service" {
		t.Errorf("the renamed service's old directory must go, got %v", got)
	}
}

// The inventory is committed beside the output, so its name and contents
// must not carry an absolute path - another checkout files the same claim.
func TestInventoryIsPortable(t *testing.T) {
	const out = "./internal/events"
	root := t.TempDir()
	genInto(t, root, "design", alphaSrc, out)
	dir := filepath.Join(root, filepath.FromSlash(out), claim.Dir)
	entries, err := os.ReadDir(dir)
	if err != nil || len(entries) != 1 {
		t.Fatalf("expected one inventory in %s: %v (%d)", dir, err, len(entries))
	}
	body, err := os.ReadFile(filepath.Join(dir, entries[0].Name()))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(body), root) || strings.Contains(entries[0].Name(), root) {
		t.Errorf("inventory carries an absolute path:\n%s\n%s", entries[0].Name(), body)
	}
	if !strings.Contains(string(body), `"design": "../../design"`) {
		t.Errorf("inventory should record the design relative to the output:\n%s", body)
	}
}

// An existing project has generated output and no inventory. The first run
// after upgrading claims what it produces and deletes nothing.
func TestFirstRunWithoutAnInventoryDeletesNothing(t *testing.T) {
	const out = "./internal/events"
	root := t.TempDir()
	genInto(t, root, "design", alphaSrc, out)
	if err := os.RemoveAll(filepath.Join(root, filepath.FromSlash(out), claim.Dir)); err != nil {
		t.Fatal(err)
	}
	genInto(t, root, "design", alphaSrc, out)
	if got := eventDirs(t, root, out); len(got) != 1 || got[0] != "alpha_service" {
		t.Errorf("an upgrade must not disturb existing output, got %v", got)
	}
}

// A generated file no inventory lists is reported, not removed: only the
// manifest that wrote one can tell a sibling's live output from a leftover.
func TestUnclaimedOutputIsReportedNotDeleted(t *testing.T) {
	const out = "./internal/events"
	root := t.TempDir()
	genInto(t, root, "design", alphaSrc, out)
	orphan := filepath.Join(root, filepath.FromSlash(out), "ghost_service", "publisher.go")
	if err := os.MkdirAll(filepath.Dir(orphan), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(orphan, []byte(generatedHeader+"\n\npackage ghost\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	cfg := eventsConfig()
	cfg.Events.Targets = []config.EventTarget{{Lang: config.LangGo, Out: out}}
	proj := analyzeProject(t, alphaSrc)
	proj.Root = filepath.Join(root, "design")

	notes := notesMatching(golang.EventOutputNotes(proj, cfg, root), "ghost_service")
	if len(notes) != 1 {
		t.Errorf("an unclaimed file must be named: %v", golang.EventOutputNotes(proj, cfg, root))
	}
	if _, err := os.Stat(orphan); err != nil {
		t.Errorf("an unclaimed file must survive: %v", err)
	}
}

// The notes reach the user for a manifest with `main: "-"`, which is what
// every deployable sharing a contract set sets.
func TestOutputNotesSurviveRuntimeDisabled(t *testing.T) {
	const out = "./internal/events"
	root := t.TempDir()
	genInto(t, root, "design", alphaSrc, out)
	orphan := filepath.Join(root, filepath.FromSlash(out), "ghost_service", "publisher.go")
	_ = os.MkdirAll(filepath.Dir(orphan), 0o755)
	_ = os.WriteFile(orphan, []byte(generatedHeader+"\n\npackage ghost\n"), 0o644)

	cfg := eventsConfig()
	cfg.Output.Main = "-"
	cfg.Events.Targets = []config.EventTarget{{Lang: config.LangGo, Out: out}}
	proj := analyzeProject(t, alphaSrc)
	proj.Root = filepath.Join(root, "design")

	if len(EventWiringNotes(proj, cfg, root)) != 0 {
		t.Error("wiring notes are for a project with a generated runtime")
	}
	if notes := notesMatching(golang.EventOutputNotes(proj, cfg, root), "ghost_service"); len(notes) != 1 {
		t.Errorf("output notes must not be gated on the runtime: %v", golang.EventOutputNotes(proj, cfg, root))
	}
}

// The inventory is committed, so a bad merge or a hand edit can put `../..`
// in one. Prune deletes what it lists, so a path escaping the output
// directory would take files craftgo never wrote.
func TestInventoryRejectsPathsOutsideTheOutput(t *testing.T) {
	const out = "./internal/events"
	root := t.TempDir()
	genInto(t, root, "design", alphaSrc, out)

	victim := filepath.Join(root, "victim", "important.go")
	if err := os.MkdirAll(filepath.Dir(victim), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(victim, []byte(generatedHeader+"\n\npackage victim\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	invDir := filepath.Join(root, filepath.FromSlash(out), claim.Dir)
	entries, _ := os.ReadDir(invDir)
	if len(entries) != 1 {
		t.Fatalf("expected one inventory, got %d", len(entries))
	}
	invPath := filepath.Join(invDir, entries[0].Name())
	poisoned := `{"design":"design","files":["alpha_service/publisher.go","../../victim/important.go","/etc/hosts",".."]}`
	if err := os.WriteFile(invPath, []byte(poisoned), 0o644); err != nil {
		t.Fatal(err)
	}

	genInto(t, root, "design", alphaSrc, out)
	if _, err := os.Stat(victim); err != nil {
		t.Errorf("a path outside the output must not be deleted: %v", err)
	}
	body, err := os.ReadFile(invPath)
	if err != nil {
		t.Fatal(err)
	}
	// The design path is relative to the output, so it legitimately
	// climbs out of it; the file list is what must stay inside.
	var written claim.Record
	if err := json.Unmarshal(body, &written); err != nil {
		t.Fatal(err)
	}
	for _, f := range written.Files {
		if !claim.Inside(f) {
			t.Errorf("an escaping path must not be written back: %q", f)
		}
	}
}

// The key is a path, so renaming the design folder files a new claim. The
// old one must stop protecting its files - otherwise a dead contract is
// both un-prunable and un-reportable. It is reported rather than deleted:
// the run that could tell live from stale is the one that is gone.
func TestInventoryForAMissingDesignIsIgnored(t *testing.T) {
	const out = "./internal/events"
	root := t.TempDir()
	genInto(t, root, "design", alphaSrc, out)

	// The same design under a new name: a fresh claim, and the old one now
	// names a folder that is gone.
	if err := os.RemoveAll(filepath.Join(root, "design")); err != nil {
		t.Fatal(err)
	}
	genInto(t, root, "renamed", `package x
type Placed { id string @minLength(1) }
service BetaService {
	event Placed { payload Placed }
}`, out)

	cfg := eventsConfig()
	cfg.Events.Targets = []config.EventTarget{{Lang: config.LangGo, Out: out}}
	proj := analyzeProject(t, alphaSrc)
	proj.Root = filepath.Join(root, "renamed")

	if notes := notesMatching(golang.EventOutputNotes(proj, cfg, root), "alpha_service"); len(notes) != 1 {
		t.Errorf("the orphaned contract must be named: %v", golang.EventOutputNotes(proj, cfg, root))
	}
	if got := eventDirs(t, root, out); len(got) != 2 {
		t.Errorf("it is reported, not deleted, got %v", got)
	}
}

// A contracts project writes none of the application half, but craftgo
// prunes none of what a project wrote while it was an application. The
// leftovers ship with the library unless someone deletes them, so they
// are named.
func TestContractsProjectNamesLeftoverApplicationOutput(t *testing.T) {
	root := t.TempDir()
	cfg := eventsConfig()
	cfg.Output.Kind = config.KindContracts
	cfg.Output.Main = "./main.go"

	stale := filepath.Join(root, filepath.FromSlash(cfg.Output.Transport), "svc", "handler.go")
	if err := os.MkdirAll(filepath.Dir(stale), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(stale, []byte(generatedHeader+"\n\npackage svc\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	notes := notesMatching(golang.EventOutputNotes(analyzeProject(t, alphaSrc), cfg, root), "output.kind is contracts")
	if len(notes) != 1 || !strings.Contains(notes[0], cfg.Output.Transport) {
		t.Errorf("leftover application output must be named: %v", notes)
	}
	if _, err := os.Stat(stale); err != nil {
		t.Errorf("it is named, not deleted: %v", err)
	}
}

// `output.main: "-"` skips the ServiceContext scaffold while the handlers,
// logic stubs and wiring are all written against it. A project that has
// not written its own is told so.
func TestRuntimeDisabledNamesTheMissingContainer(t *testing.T) {
	root := t.TempDir()
	cfg := eventsConfig()
	cfg.Output.Main = "-"
	proj := analyzeProject(t, alphaSrc)

	if notes := notesMatching(golang.EventOutputNotes(proj, cfg, root), "yours to write"); len(notes) != 1 {
		t.Errorf("a project with no container must be told: %v", golang.EventOutputNotes(proj, cfg, root))
	}

	// Once the project supplies one, the note goes.
	dest := filepath.Join(root, filepath.FromSlash(cfg.Output.Svccontext))
	if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(dest, []byte("package svccontext\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if notes := notesMatching(golang.EventOutputNotes(proj, cfg, root), "yours to write"); len(notes) != 0 {
		t.Errorf("a hand-written container must silence it: %v", notes)
	}
}

// Two designs sharing an output directory may not write one file: the
// second run would overwrite the first, leaving `make gen` ordering to
// decide which contract the directory holds.
func TestTwoDesignsCannotWriteOneFile(t *testing.T) {
	const out = "./contracts/events"
	root := t.TempDir()
	const clash = `package y
type Shipped { id string @minLength(1) }
service AlphaService {
	event Shipped { payload Shipped }
}`
	genInto(t, root, "a", alphaSrc, out)

	proj := analyzeProject(t, clash)
	proj.Root = filepath.Join(root, "b")
	if err := os.MkdirAll(proj.Root, 0o755); err != nil {
		t.Fatal(err)
	}
	cfg := eventsConfig()
	cfg.Events.Targets = []config.EventTarget{{Lang: config.LangGo, Out: out}}
	err := GenerateEventTargets(proj, cfg, root)
	if err == nil {
		t.Fatal("want a collision error, got none")
	}
	if !strings.Contains(err.Error(), "alpha_service/publisher.go") {
		t.Errorf("error must name the file, got %v", err)
	}

	// The first design's output is untouched: the check runs before any
	// file is written.
	body, readErr := os.ReadFile(filepath.Join(root, out, "alpha_service", "publisher.go"))
	if readErr != nil {
		t.Fatal(readErr)
	}
	if !strings.Contains(string(body), "package x") {
		t.Errorf("the first design's file was overwritten: %s", firstLines(string(body)))
	}
}

func firstLines(s string) string {
	if parts := strings.SplitN(s, "\n", 4); len(parts) > 3 {
		return strings.Join(parts[:3], "\n")
	}
	return s
}

// Two manifests sharing an output need not share a project root: a
// deployable generating handlers under the repo root and the contract set
// generating types beside itself are rooted differently. The claim is
// keyed to the output, so each still reads the other's.
func TestClaimsAreReadableFromAnotherProjectRoot(t *testing.T) {
	const out = "./contracts/events"
	repo := t.TempDir()
	inner := filepath.Join(repo, "contracts")
	if err := os.MkdirAll(inner, 0o755); err != nil {
		t.Fatal(err)
	}

	// The contract set writes from inside contracts/, the deployable from
	// the repo root, both into the same directory.
	genInto(t, inner, "design", alphaSrc, "./events")
	genInto(t, repo, "service/audit/design", betaSrc, out)

	got := eventDirs(t, inner, "./events")
	if len(got) != 2 {
		t.Fatalf("both manifests' output must survive, got %v", got)
	}

	// The deployable drops its last event: its own output goes, the
	// contract set's stays.
	genInto(t, repo, "service/audit/design", `package y
type Shipped { id string @minLength(1) }
service BetaService {
	get List /list { response Shipped }
}`, out)
	got = eventDirs(t, inner, "./events")
	if len(got) != 1 || got[0] != "alpha_service" {
		t.Errorf("the other root's claim must still protect it, got %v", got)
	}
}

// The events output is regenerated wholesale, so a publisher left behind by
// a renamed service must not survive: in a published contract package it
// would still export a contract the design no longer declares.
func TestStaleGeneratedEventFilesArePruned(t *testing.T) {
	dir := t.TempDir()
	cfg := eventsConfig()

	before := analyzeProject(t, `package orders
type P { id string }
service OrderService {
	event OrderPlaced { payload P }
}`)
	if err := GenerateEventTargets(before, cfg, dir); err != nil {
		t.Fatalf("generate: %v", err)
	}
	stale := filepath.Join(dir, "internal", "events", "order_service", "publisher.go")
	if _, err := os.Stat(stale); err != nil {
		t.Fatalf("first run wrote no publisher: %v", err)
	}
	// A file the user put here is not ours to delete.
	mine := filepath.Join(dir, "internal", "events", "order_service", "helper.go")
	if err := os.WriteFile(mine, []byte("package orders\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	after := analyzeProject(t, `package orders
type P { id string }
service BillingService {
	event OrderPlaced { payload P }
}`)
	if err := GenerateEventTargets(after, cfg, dir); err != nil {
		t.Fatalf("regenerate: %v", err)
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Errorf("the renamed service's old publisher survived (%v)", err)
	}
	if _, err := os.Stat(mine); err != nil {
		t.Errorf("a hand-written file was deleted: %v", err)
	}
	fresh := filepath.Join(dir, "internal", "events", "billing_service", "publisher.go")
	if _, err := os.Stat(fresh); err != nil {
		t.Errorf("the renamed service has no publisher: %v", err)
	}
}
