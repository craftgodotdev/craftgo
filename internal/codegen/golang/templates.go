package golang

import (
	"bytes"
	"embed"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sync"
	"text/template"
)

// GeneratedHeader opens every Go file craftgo rewrites on each run.
const GeneratedHeader = "// Code generated by craftgo. DO NOT EDIT."

// scaffoldHeader opens every gen-once Go file craftgo writes.
const scaffoldHeader = "// Scaffold generated by craftgo. Safe to edit; will not be overwritten."

// builtinTemplates embeds every codegen template.
//
//go:embed templates/*.tmpl
var builtinTemplates embed.FS

// tmplCache holds each parsed template by name; a parsed template is safe for concurrent execution.
var tmplCache sync.Map // name → *template.Template

// tmpl returns the named template, parsing it on first use; a missing or broken template panics.
func tmpl(name string) *template.Template {
	if t, ok := tmplCache.Load(name); ok {
		return t.(*template.Template)
	}
	t, err := template.ParseFS(builtinTemplates, "templates/"+name)
	if err != nil {
		panic(fmt.Sprintf("codegen: parse %s: %v", name, err))
	}
	actual, _ := tmplCache.LoadOrStore(name, t)
	return actual.(*template.Template)
}

// execute runs t with data.
func execute(t *template.Template, data any) ([]byte, error) {
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("execute template %q: %w", t.Name(), err)
	}
	return buf.Bytes(), nil
}

// renderGo renders t as a regenerated Go file: [GeneratedHeader], a blank line, then t's source.
func renderGo(t *template.Template, data any) ([]byte, error) {
	src, err := execute(t, data)
	if err != nil {
		return nil, err
	}
	return generatedGo(src)
}

// renderScaffold renders t as a gen-once Go file: [scaffoldHeader], then t's source, whose first
// line may continue the header's comment.
func renderScaffold(t *template.Template, data any) ([]byte, error) {
	src, err := execute(t, data)
	if err != nil {
		return nil, err
	}
	return formatGo(append([]byte(scaffoldHeader+"\n"), src...))
}

// generatedGo gofmts src, a package clause onward, below [GeneratedHeader].
func generatedGo(src []byte) ([]byte, error) {
	return formatGo(append([]byte(GeneratedHeader+"\n\n"), src...))
}

func formatGo(src []byte) ([]byte, error) {
	formatted, err := format.Source(src)
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w\n--- source ---\n%s", err, src)
	}
	return formatted, nil
}

// writeGo writes t's regenerated Go file to path.
func writeGo(path string, t *template.Template, data any) error {
	return writeRendered(path, func() ([]byte, error) { return renderGo(t, data) })
}

// writeGoSource writes the regenerated Go file whose source, from the package clause on, is src.
func writeGoSource(path, src string) error {
	return writeRendered(path, func() ([]byte, error) { return generatedGo([]byte(src)) })
}

// writeGoOnce writes t's gen-once Go file to path unless a file is already there.
func writeGoOnce(path string, t *template.Template, data any) error {
	if fileExists(path) {
		return nil
	}
	return writeRendered(path, func() ([]byte, error) { return renderScaffold(t, data) })
}

// writeTextOnce writes t's output to path unless a file is already there.
func writeTextOnce(path string, t *template.Template, data any) error {
	if fileExists(path) {
		return nil
	}
	return writeRendered(path, func() ([]byte, error) { return execute(t, data) })
}

// writeRendered writes what render returns to path, creating its directory.
func writeRendered(path string, render func() ([]byte, error)) error {
	body, err := render()
	if err != nil {
		return fmt.Errorf("render %s: %w", filepath.Base(path), err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, body, 0o644)
}

func fileExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}
