// GenerateEventTarget is the Go row of the language-target catalogue: it
// emits every package's publishers, consumer subscriptions and logic
// stubs, then the project-wide Subscribe and the svccontext container.
//
// The publishers and the Consumers interface are the contract half: they
// come from the whole design, land under the root that half resolves
// against, and are what two deployables of one design write identically.
// The adapters and logic stubs bind to a container, so they follow what
// this project deploys.
func GenerateEventTarget(proj *semantic.Project, cfg *config.Config, projectRoot, outDir string) error {
	design, libraryRoot := proj.Design(), cfg.LibraryRoot(projectRoot)
	for _, name := range sortedPackageNames(design) {
		r := buildProjectResolver(design, cfg, name)
		if err := generatePackageContracts(design.Packages[name], cfg, libraryRoot, outDir, r); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
	}
	// The adapter, the logic stub and SubscribeAll all reach into the
	// transport packages and the container, so they belong to a
	// deployable rather than to the contract set.
	if !cfg.Output.ContractsOnly() {
		for _, name := range sortedPackageNames(proj) {
			r := buildProjectResolver(proj, cfg, name)
			if err := generatePackageConsumers(proj.Packages[name], cfg, projectRoot, r); err != nil {
				return fmt.Errorf("%s: %w", name, err)
			}
		}
		if err := generateProjectEvents(proj, cfg, projectRoot, outDir); err != nil {
			return err
		}
	}
	return pruneEventOutput(design, cfg, libraryRoot, outDir)
}

// generatedHeader marks a file this package rewrites on every run. The
// scaffolds carry a different first line and are never touched.
const generatedHeader = "// Code generated by craftgo. DO NOT EDIT."

// pruneEventOutput deletes generated files under outDir that this design no
// longer produces - a publisher left behind by a renamed or deleted service,
// say. Without it the directory accumulates contracts the design has
// dropped, which is dead code in an application and a live hazard once the
// directory is published as a library: an importer can still reach a
// contract nobody declares.
//
// Several manifests may write into one output directory so a contract set
// has a single Go copy. A run therefore deletes only what its own design's
// previous run produced and no other design claims - see [claim]. A file
// nobody claims is reported by [unclaimedEventFiles] rather than guessed
// at.
//
// Only files carrying [generatedHeader] are removed, so a hand-written file
// or a scaffold that happens to sit here survives.
func pruneEventOutput(proj *semantic.Project, cfg *config.Config, libraryRoot, outDir string) error {
	root := filepath.Join(libraryRoot, outDir)
	if _, err := os.Stat(root); err != nil {
		return nil
	}
	keep := expectedEventFiles(proj, cfg, libraryRoot, outDir)
	mine := claim.Name(claim.Key(root, proj.Root))
	records := claim.Live(claim.Read(root), root)
	foreign := claim.Foreign(root, mine)

	var dirs []string
	for _, rel := range records[mine].Files {
		path := filepath.Join(root, filepath.FromSlash(rel))
		if _, taken := foreign[path]; taken {
			continue
		}
		if keep[path] || !isGeneratedFile(path) {
			continue
		}
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return err
		}
		dirs = append(dirs, filepath.Dir(path))
	}

	// Drop directories the removals emptied, deepest first.
	sort.Sort(sort.Reverse(sort.StringSlice(dirs)))
	for _, dir := range dirs {
		entries, err := os.ReadDir(dir)
		if err == nil && len(entries) == 0 {
			_ = os.Remove(dir)
		}
	}
	return nil
}

// expectedEventFiles is the set of files this run produces under outDir.
func expectedEventFiles(proj *semantic.Project, cfg *config.Config, libraryRoot, outDir string) map[string]bool {
	keep := map[string]bool{}
	for _, name := range sortedPackageNames(proj) {
		pkg := proj.Packages[name]
		if pkg == nil {
			continue
		}
		for _, svcName := range sortedServices(pkg) {
			svc := pkg.Services[svcName]
			dir := publisherDir(libraryRoot, outDir, svcName, cfg.Output.FileCase)
			if len(svc.Events) > 0 {
				keep[filepath.Join(dir, "publisher.go")] = true
			}
			if len(svc.Consumers) > 0 {
				keep[filepath.Join(dir, "consumers.go")] = true
			}
		}
	}
	return keep
}

// appSideDirs are the outputs a contracts project does not write. Flipping
// a project to `kind: contracts` leaves whatever it wrote as an
// application on disk, and craftgo prunes none of it.
func appSideDirs(cfg *config.Config) []struct{ key, path string } {
	return []struct{ key, path string }{
		{"output.transport", cfg.Output.Transport},
		{"output.routes", cfg.Output.Routes},
		{"output.service", cfg.Output.Service},
		{"output.wiring", cfg.Output.Wiring},
		{"output.middleware", cfg.Output.Middleware},
		{"output.config", cfg.Output.Config},
		{"output.svccontext", fileDirRel(cfg.Output.Svccontext)},
	}
}

// staleApplicationOutput reports application output still on disk under a
// contracts project. It is named rather than removed: craftgo did not
// record writing it, so it cannot tell its own leftovers from a directory
// the project uses for something else.
func staleApplicationOutput(cfg *config.Config, projectRoot string) []string {
	if !cfg.Output.ContractsOnly() {
		return nil
	}
	var found []string
	for _, d := range appSideDirs(cfg) {
		if d.path == "" || d.path == "-" {
			continue
		}
		if hasGeneratedFile(filepath.Join(projectRoot, d.path)) {
			found = append(found, d.path)
		}
	}
	if main := cfg.Output.Main; main != "" && main != "-" && isScaffoldFile(filepath.Join(projectRoot, main)) {
		found = append(found, main)
	}
	if len(found) == 0 {
		return nil
	}
	sort.Strings(found)
	return []string{"output.kind is contracts but " + strings.Join(found, ", ") +
		" still hold generated application files - delete them, or they ship with the contract library"}
}

// hasGeneratedFile reports whether dir holds a file craftgo wrote.
func hasGeneratedFile(dir string) bool {
	found := false
	_ = filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || filepath.Ext(path) != ".go" || found {
			return nil
		}
		if isGeneratedFile(path) || isScaffoldFile(path) {
			found = true
		}
		return nil
	})
	return found
}

// isScaffoldFile reports whether the file opens with the gen-once header.
func isScaffoldFile(path string) bool {
	body, err := os.ReadFile(path)
	return err == nil && strings.HasPrefix(string(body), "// Scaffold generated by craftgo")
}

// missingContainerNote reports that the generated code needs a
// ServiceContext the project opted out of scaffolding. `output.main: "-"`
// skips svccontext.go, and the handlers, logic stubs and wiring are all
// written against the type it would have declared.
func missingContainerNote(cfg *config.Config, projectRoot string) []string {
	if !cfg.Output.RuntimeDisabled() || cfg.Output.ContractsOnly() {
		return nil
	}
	dest := filepath.Join(projectRoot, cfg.Output.Svccontext)
	if _, err := os.Stat(dest); err == nil {
		return nil
	}
	return []string{"output.main is \"-\", so " + cfg.Output.Svccontext +
		" is yours to write - the generated handlers and wiring need a ServiceContext type there"}
}

// EventOutputNotes reports what the Go event output holds that this run
// cannot account for.
func EventOutputNotes(proj *semantic.Project, cfg *config.Config, projectRoot string) []string {
	out := staleApplicationOutput(cfg, projectRoot)
	out = append(out, missingContainerNote(cfg, projectRoot)...)
	return append(out, unclaimedEventFiles(proj, cfg, projectRoot)...)
}

// unclaimedEventFiles reports generated files under the Go event output
// that no claim lists. They are left alone - only the design that wrote
// one can tell a sibling's live output from a leftover - so naming them
// is the whole of what craftgo can say.
func unclaimedEventFiles(proj *semantic.Project, cfg *config.Config, projectRoot string) []string {
	target, ok := cfg.Events.TargetFor(config.LangGo)
	if !ok || !target.Enabled() {
		return nil
	}
	libraryRoot := cfg.LibraryRoot(projectRoot)
	root := filepath.Join(libraryRoot, target.Out)
	if _, err := os.Stat(root); err != nil {
		return nil
	}
	claimed := map[string]bool{}
	for _, rec := range claim.Live(claim.Read(root), root) {
		for _, f := range rec.Files {
			claimed[filepath.Join(root, filepath.FromSlash(f))] = true
		}
	}
	var out []string
	_ = filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || filepath.Ext(path) != ".go" {
			return nil
		}
		if claimed[path] || !isGeneratedFile(path) {
			return nil
		}
		rel, relErr := filepath.Rel(libraryRoot, path)
		if relErr != nil {
			rel = path
		}
		out = append(out, rel)
		return nil
	})
	sort.Strings(out)
	if len(out) == 0 {
		return nil
	}
	return []string{"no manifest claims " + strings.Join(out, ", ") +
		" - re-run the design that writes them, or delete them if stale"}
}

// isGeneratedFile reports whether the file opens with [generatedHeader].
func isGeneratedFile(path string) bool {
	body, err := os.ReadFile(path)
	return err == nil && strings.HasPrefix(string(body), generatedHeader)
}

// eventsEnabled reports whether the Go event artefacts are generated:
// the design declares an event and the Go target is configured and on.
// The scaffolds that reference those artefacts read this, not
// [semantic.Project.HasEvents] alone.
func eventsEnabled(proj *semantic.Project, cfg *config.Config) bool {
	if !proj.HasEvents() {
		return false
	}
	target, ok := cfg.Events.TargetFor(config.LangGo)
	return ok && target.Enabled()
}

// EventWiringNotes reports what a project still has to wire by hand. The
// `svccontext.go` and `main.go` scaffolds are gen-once, so a design that
// gains its first event leaves them untouched: the publishers exist but
// nothing reaches them and no consumer subscribes.
func EventWiringNotes(proj *semantic.Project, cfg *config.Config, projectRoot string) []string {
	if cfg.Output.RuntimeDisabled() || cfg.Output.ContractsOnly() {
		return nil
	}
	mainPath := filepath.Join(projectRoot, cfg.Output.Main)
	// main.go is written once, so moving `output.wiring` leaves it
	// compiling against the copy at the old path.
	wiringImport := goImportFromRel(cfg.Package, cfg.Output.Wiring)
	if fileMentions(mainPath, "wiring.Register(") && !fileMentions(mainPath, `"`+wiringImport+`"`) {
		return []string{cfg.Output.Main + " imports a wiring package other than " + wiringImport +
			" - it is generated once, so point its import at output.wiring and delete the directory the key used to name"}
	}
	if !eventsEnabled(proj, cfg) {
		return nil
	}
	var out []string
	if !fileMentions(filepath.Join(projectRoot, cfg.Output.Svccontext), "Events Events") {
		out = append(out, "add `Events Events` to your ServiceContext in "+cfg.Output.Svccontext+" - the generated publishers hang off it")
	}
	if !fileMentions(filepath.Join(projectRoot, cfg.Output.Main), "svccontext.NewEvents(") {
		out = append(out, "build the event bus in "+cfg.Output.Main+" and assign `svc.Events = svccontext.NewEvents(bus)` - see the Events guide")
	}
	// A main.go that never calls Register subscribes nothing, and its HTTP
	// side keeps working, so the build says nothing either.
	if len(proj.Consumers()) > 0 && !fileMentions(filepath.Join(projectRoot, cfg.Output.Main), "wiring.Register(") {
		out = append(out, "call `wiring.Register(ctx, srv, svc)` in "+cfg.Output.Main+
			" - it replaces `routes.RegisterAll` and `transport.SubscribeAll`; until it does, the generated consumers are never subscribed")
	}
	return out
}

// fileMentions reports whether the file at path exists and contains
// needle. A missing file counts as not mentioning it.
func fileMentions(path, needle string) bool {
	body, err := os.ReadFile(path)
	return err == nil && strings.Contains(string(body), needle)
}

// removeGenerated deletes a file this package wrote on an earlier run.
// A hand-written file at the same path is left alone, so a design that
// stops producing an artefact cannot strand one that still references a
// package the run no longer emits.
func removeGenerated(path string) {
	if isGeneratedFile(path) {
		_ = os.Remove(path)
	}
}
