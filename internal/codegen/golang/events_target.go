// GenerateEventTarget is the Go row of the language-target catalogue: it
// emits one library per DSL package - the contract descriptors.
//
// The library is pure contract, so it is generated the same whatever the
// project deploys: a contracts project writes it and stops, and an
// application project writes its HTTP half around it.
func GenerateEventTarget(proj *semantic.Project, cfg *config.Config, projectRoot, outDir string) error {
	for _, name := range sortedPackageNames(proj) {
		r := buildProjectResolver(proj, cfg, name)
		if err := generatePackageEvents(proj.Packages[name], cfg, projectRoot, outDir, r); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
	}
	return nil
}

// generatedHeader opens every file this package rewrites on each run.
// The scaffolds carry a different first line and are never touched.
const generatedHeader = "// Code generated by craftgo. DO NOT EDIT."

// expectedEventFiles is the set of files this run produces under root,
// the event target's own directory.
func expectedEventFiles(proj *semantic.Project, root string) map[string]bool {
	keep := map[string]bool{}
	for _, name := range sortedPackageNames(proj) {
		pkg := proj.Packages[name]
		if pkg == nil || len(pkg.Events) == 0 {
			continue
		}
		keep[filepath.Join(root, name, "events.go")] = true
	}
	return keep
}

// appSideDirs are the outputs a contracts project does not write. Flipping
// a project to `kind: contracts` leaves whatever it wrote as an
// application on disk, and craftgo prunes none of it.
func appSideDirs(cfg *config.Config) []struct{ key, path string } {
	return []struct{ key, path string }{
		{"output.transport", cfg.Output.Transport},
		{"output.routes", cfg.Output.Routes},
		{"output.service", cfg.Output.Service},
		{"output.wiring", cfg.Output.Wiring},
		{"output.grpc", cfg.Output.GRPC},
		{"output.middleware", cfg.Output.Middleware},
		{"output.config", cfg.Output.Config},
		{"output.svccontext", fileDirRel(cfg.Output.Svccontext)},
	}
}

// staleApplicationOutput reports application output still on disk under a
// contracts project. It is named rather than removed: the run writes none
// of those directories, so none of them is swept and craftgo cannot tell
// its own leftovers from a directory the project uses for something else.
func staleApplicationOutput(cfg *config.Config, projectRoot string) []string {
	if !cfg.Output.ContractsOnly() {
		return nil
	}
	var found []string
	for _, d := range appSideDirs(cfg) {
		if d.path == "" || d.path == "-" {
			continue
		}
		if hasGeneratedFile(filepath.Join(projectRoot, d.path)) {
			found = append(found, d.path)
		}
	}
	if main := cfg.Output.Main; main != "" && main != "-" && isScaffoldFile(filepath.Join(projectRoot, main)) {
		found = append(found, main)
	}
	if len(found) == 0 {
		return nil
	}
	sort.Strings(found)
	return []string{"output.kind is contracts but " + strings.Join(found, ", ") +
		" still hold generated application files - delete them, or they ship with the contract library"}
}

// hasGeneratedFile reports whether dir holds a file craftgo wrote.
func hasGeneratedFile(dir string) bool {
	found := false
	_ = filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || filepath.Ext(path) != ".go" || found {
			return nil
		}
		if isGeneratedFile(path) || isScaffoldFile(path) {
			found = true
		}
		return nil
	})
	return found
}

// isScaffoldFile reports whether the file opens with the gen-once header.
func isScaffoldFile(path string) bool {
	body, err := os.ReadFile(path)
	return err == nil && strings.HasPrefix(string(body), "// Scaffold generated by craftgo")
}

// isGeneratedFile reports whether the file opens with [generatedHeader].
func isGeneratedFile(path string) bool {
	body, err := os.ReadFile(path)
	return err == nil && strings.HasPrefix(string(body), generatedHeader)
}

// missingContainerNote reports that the generated code needs a
// ServiceContext the project opted out of scaffolding. `output.main: "-"`
// skips svccontext.go, and the handlers, logic stubs and wiring are all
// written against the type it would have declared.
func missingContainerNote(cfg *config.Config, projectRoot string) []string {
	if !cfg.Output.RuntimeDisabled() || cfg.Output.ContractsOnly() {
		return nil
	}
	dest := filepath.Join(projectRoot, cfg.Output.Svccontext)
	if _, err := os.Stat(dest); err == nil {
		return nil
	}
	return []string{"output.main is \"-\", so " + cfg.Output.Svccontext +
		" is yours to write - the generated handlers and wiring need a ServiceContext type there"}
}

// EventOutputNotes reports what the Go output holds that this run cannot
// account for.
func EventOutputNotes(proj *semantic.Project, protos *protodesign.Set, cfg *config.Config, projectRoot string) []string {
	out := staleApplicationOutput(cfg, projectRoot)
	out = append(out, missingContainerNote(cfg, projectRoot)...)
	out = append(out, staleWiringImport(cfg, projectRoot)...)
	out = append(out, scaffoldGapNotes(proj, protos, cfg, projectRoot)...)
	return append(out, orphanedStubNotes(proj, protos, cfg, projectRoot)...)
}

// orphanedStubNotes names the logic directories under output.service
// whose service - HTTP or gRPC - the design no longer declares. The stubs
// are the user's and are never swept, but they import the types or the
// pb package of the service they were written for, which the sweep has
// taken, so the project no longer builds until they are moved or
// deleted.
func orphanedStubNotes(proj *semantic.Project, protos *protodesign.Set, cfg *config.Config, projectRoot string) []string {
	if cfg.Output.ContractsOnly() {
		return nil
	}
	owned := map[string]bool{}
	if proj != nil {
		for _, name := range sortedPackageNames(proj) {
			pkg := proj.Packages[name]
			if pkg == nil {
				continue
			}
			for _, svcName := range sortedServices(pkg) {
				for _, group := range distinctGroups(pkg.Services[svcName]) {
					owned[outputSegFor(svcName, group, cfg.Output.FileCase)] = true
				}
			}
		}
	}
	if protos != nil {
		for _, svc := range protos.Services {
			owned[svc.Dir] = true
		}
	}
	root := filepath.Join(projectRoot, cfg.Output.Service)
	orphaned := map[string]bool{}
	_ = filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !fileStartsWith(path, scaffoldHeader) {
			return nil
		}
		rel, err := filepath.Rel(root, filepath.Dir(path))
		if err != nil {
			return nil
		}
		if dir := filepath.ToSlash(rel); !owned[dir] {
			orphaned[dir] = true
		}
		return nil
	})
	var out []string
	for _, dir := range sortedKeys(orphaned) {
		out = append(out, cfg.Output.Service+"/"+dir+" holds logic stubs of a service the design no longer declares - the generated code they import is gone, so move or delete them")
	}
	return out
}

// scaffoldHeader opens every gen-once file craftgo writes.
const scaffoldHeader = "// Scaffold generated by craftgo."

// fileStartsWith reports whether the file at path exists and opens with
// prefix.
func fileStartsWith(path, prefix string) bool {
	body, err := os.ReadFile(path)
	return err == nil && strings.HasPrefix(string(body), prefix)
}

// scaffoldGapNotes reports a gen-once scaffold that predates the design's
// current transports. main.go and config.go are written once, so a
// project that gains its first proto service after they were written -
// or its first HTTP route - has a wiring call the design needs and the
// scaffold does not make.
func scaffoldGapNotes(proj *semantic.Project, protos *protodesign.Set, cfg *config.Config, projectRoot string) []string {
	if cfg.Output.RuntimeDisabled() || cfg.Output.ContractsOnly() {
		return nil
	}
	mainPath := filepath.Join(projectRoot, cfg.Output.Main)
	configPath := filepath.Join(projectRoot, cfg.Output.Config, "config.go")
	var out []string
	if _, err := os.Stat(mainPath); err == nil {
		if protos.HasServices() && !fileMentions(mainPath, "wiring.RegisterGRPC(") {
			out = append(out, cfg.Output.Main+" predates the gRPC services and never calls wiring.RegisterGRPC - it is generated once, so add the gRPC listener block by hand (docs/guide/grpc.md shows it)")
		}
		if !protos.HasServices() && fileMentions(mainPath, "wiring.RegisterGRPC(") {
			out = append(out, cfg.Output.Main+" still boots a gRPC listener, but the design declares no proto service and "+cfg.Output.Wiring+"/grpc.go is gone - it is generated once, so remove the gRPC block by hand (or restore the proto)")
		}
		if projectHasRoutes(proj) && !fileMentions(mainPath, "wiring.Register(") {
			out = append(out, cfg.Output.Main+" predates the HTTP routes and never calls wiring.Register - it is generated once, so add the HTTP listener block by hand (docs/guide/runtime.md shows it)")
		}
	}
	if _, err := os.Stat(configPath); err == nil && protos.HasServices() && !fileMentions(configPath, "GRPCConfig") {
		out = append(out, cfg.Output.Config+"/config.go predates the gRPC services and has no GRPCConfig - it is generated once, so add the `grpc:` block by hand (docs/guide/grpc.md shows it)")
	}
	if protos != nil && cfg.Output.PBDisabled() {
		for _, svc := range protos.Services {
			rel, ok := strings.CutPrefix(svc.PBImport, cfg.Package+"/")
			if !ok {
				continue
			}
			if matches, _ := filepath.Glob(filepath.Join(projectRoot, filepath.FromSlash(rel), "*.pb.go")); len(matches) == 0 {
				out = append(out, "output.pb is \"-\" and "+rel+" holds no .pb.go yet - the generated gRPC layer imports it, so run your protoc/buf pipeline before `go build`")
			}
		}
	}
	return out
}

// staleWiringImport reports a main.go calling a wiring package other than
// the one `output.wiring` names. main.go is written once, so moving the
// key leaves it compiling against the copy at the old path.
func staleWiringImport(cfg *config.Config, projectRoot string) []string {
	if cfg.Output.RuntimeDisabled() || cfg.Output.ContractsOnly() {
		return nil
	}
	mainPath := filepath.Join(projectRoot, cfg.Output.Main)
	wiringImport := goImportFromRel(cfg.Package, cfg.Output.Wiring)
	if !fileMentions(mainPath, "wiring.Register(") || fileMentions(mainPath, `"`+wiringImport+`"`) {
		return nil
	}
	return []string{cfg.Output.Main + " imports a wiring package other than " + wiringImport +
		" - it is generated once, so point its import at output.wiring and delete the directory the key used to name"}
}

// fileMentions reports whether the file at path exists and contains
// needle. A missing file counts as not mentioning it.
func fileMentions(path, needle string) bool {
	body, err := os.ReadFile(path)
	return err == nil && strings.Contains(string(body), needle)
}
