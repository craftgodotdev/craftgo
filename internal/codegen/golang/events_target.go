// GenerateEventTarget is the Go row of the language-target catalogue: it
// emits one library per DSL package - the contract descriptors.
//
// The library is pure contract, so it is generated the same whatever the
// project deploys: a contracts project writes it and stops, and an
// application project writes its HTTP half around it.
func GenerateEventTarget(proj *semantic.Project, cfg *config.Config, projectRoot, outDir string) error {
	for _, name := range sortedPackageNames(proj) {
		r := buildProjectResolver(proj, cfg, name)
		if err := generatePackageEvents(proj.Packages[name], cfg, projectRoot, outDir, r); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
	}
	return nil
}

// generatedHeader opens every file this package rewrites on each run.
// The scaffolds carry a different first line and are never touched.
// [claim.Generated] is the reader of it.
const generatedHeader = "// Code generated by craftgo. DO NOT EDIT."

// expectedEventFiles is the set of files this run produces under root,
// the event target's own directory.
func expectedEventFiles(proj *semantic.Project, root string) map[string]bool {
	keep := map[string]bool{}
	for _, name := range sortedPackageNames(proj) {
		pkg := proj.Packages[name]
		if pkg == nil || len(pkg.Events) == 0 {
			continue
		}
		keep[filepath.Join(root, name, "events.go")] = true
	}
	return keep
}

// appSideDirs are the outputs a contracts project does not write. Flipping
// a project to `kind: contracts` leaves whatever it wrote as an
// application on disk, and craftgo prunes none of it.
func appSideDirs(cfg *config.Config) []struct{ key, path string } {
	return []struct{ key, path string }{
		{"output.transport", cfg.Output.Transport},
		{"output.routes", cfg.Output.Routes},
		{"output.service", cfg.Output.Service},
		{"output.wiring", cfg.Output.Wiring},
		{"output.middleware", cfg.Output.Middleware},
		{"output.config", cfg.Output.Config},
		{"output.svccontext", fileDirRel(cfg.Output.Svccontext)},
	}
}

// staleApplicationOutput reports application output still on disk under a
// contracts project. It is named rather than removed: craftgo did not
// record writing it, so it cannot tell its own leftovers from a directory
// the project uses for something else.
func staleApplicationOutput(cfg *config.Config, projectRoot string) []string {
	if !cfg.Output.ContractsOnly() {
		return nil
	}
	var found []string
	for _, d := range appSideDirs(cfg) {
		if d.path == "" || d.path == "-" {
			continue
		}
		if hasGeneratedFile(filepath.Join(projectRoot, d.path)) {
			found = append(found, d.path)
		}
	}
	if main := cfg.Output.Main; main != "" && main != "-" && isScaffoldFile(filepath.Join(projectRoot, main)) {
		found = append(found, main)
	}
	if len(found) == 0 {
		return nil
	}
	sort.Strings(found)
	return []string{"output.kind is contracts but " + strings.Join(found, ", ") +
		" still hold generated application files - delete them, or they ship with the contract library"}
}

// hasGeneratedFile reports whether dir holds a file craftgo wrote.
func hasGeneratedFile(dir string) bool {
	found := false
	_ = filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || filepath.Ext(path) != ".go" || found {
			return nil
		}
		if claim.Generated(path) || isScaffoldFile(path) {
			found = true
		}
		return nil
	})
	return found
}

// isScaffoldFile reports whether the file opens with the gen-once header.
func isScaffoldFile(path string) bool {
	body, err := os.ReadFile(path)
	return err == nil && strings.HasPrefix(string(body), "// Scaffold generated by craftgo")
}

// missingContainerNote reports that the generated code needs a
// ServiceContext the project opted out of scaffolding. `output.main: "-"`
// skips svccontext.go, and the handlers, logic stubs and wiring are all
// written against the type it would have declared.
func missingContainerNote(cfg *config.Config, projectRoot string) []string {
	if !cfg.Output.RuntimeDisabled() || cfg.Output.ContractsOnly() {
		return nil
	}
	dest := filepath.Join(projectRoot, cfg.Output.Svccontext)
	if _, err := os.Stat(dest); err == nil {
		return nil
	}
	return []string{"output.main is \"-\", so " + cfg.Output.Svccontext +
		" is yours to write - the generated handlers and wiring need a ServiceContext type there"}
}

// EventOutputNotes reports what the Go output holds that this run cannot
// account for.
func EventOutputNotes(proj *semantic.Project, cfg *config.Config, projectRoot string) []string {
	out := staleApplicationOutput(cfg, projectRoot)
	out = append(out, missingContainerNote(cfg, projectRoot)...)
	out = append(out, staleWiringImport(cfg, projectRoot)...)
	return append(out, unclaimedEventFiles(proj, cfg, projectRoot)...)
}

// staleWiringImport reports a main.go calling a wiring package other than
// the one `output.wiring` names. main.go is written once, so moving the
// key leaves it compiling against the copy at the old path.
func staleWiringImport(cfg *config.Config, projectRoot string) []string {
	if cfg.Output.RuntimeDisabled() || cfg.Output.ContractsOnly() {
		return nil
	}
	mainPath := filepath.Join(projectRoot, cfg.Output.Main)
	wiringImport := goImportFromRel(cfg.Package, cfg.Output.Wiring)
	if !fileMentions(mainPath, "wiring.Register(") || fileMentions(mainPath, `"`+wiringImport+`"`) {
		return nil
	}
	return []string{cfg.Output.Main + " imports a wiring package other than " + wiringImport +
		" - it is generated once, so point its import at output.wiring and delete the directory the key used to name"}
}

// unclaimedEventFiles reports generated files under the Go event output
// that no claim lists. They are left alone - only the design that wrote
// one can tell a sibling's live output from a leftover - so naming them
// is the whole of what craftgo can say.
func unclaimedEventFiles(proj *semantic.Project, cfg *config.Config, projectRoot string) []string {
	target, ok := cfg.Events.TargetFor(config.LangGo)
	if !ok || !target.Enabled() {
		return nil
	}
	root := filepath.Join(projectRoot, target.Out)
	if _, err := os.Stat(root); err != nil {
		return nil
	}
	claimed := map[string]bool{}
	for _, rec := range claim.Live(claim.Read(root), root) {
		for _, f := range rec.Files {
			claimed[filepath.Join(root, filepath.FromSlash(f))] = true
		}
	}
	var out []string
	_ = filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || filepath.Ext(path) != ".go" {
			return nil
		}
		if claimed[path] || !claim.Generated(path) {
			return nil
		}
		rel, relErr := filepath.Rel(projectRoot, path)
		if relErr != nil {
			rel = path
		}
		out = append(out, rel)
		return nil
	})
	sort.Strings(out)
	if len(out) == 0 {
		return nil
	}
	return []string{"no manifest claims " + strings.Join(out, ", ") +
		" - re-run the design that writes them, or delete them if stale"}
}

// fileMentions reports whether the file at path exists and contains
// needle. A missing file counts as not mentioning it.
func fileMentions(path, needle string) bool {
	body, err := os.ReadFile(path)
	return err == nil && strings.Contains(string(body), needle)
}

// removeGenerated deletes a file this package wrote on an earlier run.
// A hand-written file at the same path is left alone, so a design that
// stops producing an artefact cannot strand one that still references a
// package the run no longer emits.
func removeGenerated(path string) {
	if claim.Generated(path) {
		_ = os.Remove(path)
	}
}
